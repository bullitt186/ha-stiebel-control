#!/usr/bin/env python3
"""Entity IDs in dashboards/*.yaml must be IDs the firmware generates (#96).

The firmware sends default_entity_id = <domain>.<root>_<unique_id without "stiebel_">
(root "heatingpump"). This check rebuilds the possible suffixes from the sources:
- raw signals:      <member>_<signal> (CanMembers[] x ElsterTable[] names), numbers add "_set"
- calculated/COP:   unique IDs of calculatedSensors[] and the fault list
- selects/climate:  writableSelects[] rows, climate_heizung(_hk2) / climate_warmwasser
- time programs:    ww_programm_<day>, heiz_programm_<day>, heiz_programm_hk2_<day>
- ESPHome entities: <root>_<slug of a `name:` in esphome/ha-stiebel-control/*.yaml>
Exit 1 if a dashboard references an ID outside this set.
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "esphome" / "ha-stiebel-control"
PREFIX = "heatingpump_"
DOMAINS = r"(?:sensor|binary_sensor|number|select|climate|text|button|switch)"
DAYS = ["mo", "di", "mi", "do", "fr", "sa", "so"]


def slug(text: str) -> str:
    text = text.lower()
    for a, b in (("ä", "a"), ("ö", "o"), ("ü", "u"), ("ß", "ss")):
        text = text.replace(a, b)
    return re.sub(r"[^a-z0-9]+", "_", text).strip("_")


def allowed_suffixes() -> set:
    header = (SRC / "ha-stiebel-control.h").read_text(encoding="utf-8")
    members = re.findall(r'\{"([A-Z0-9_]+)",\s*0x[0-9a-fA-F]+\}', (SRC / "can_members.h").read_text(encoding="utf-8"))
    signals = re.findall(r'\{\s*"([A-Z0-9_]+)"\s*,\s*0x[0-9a-fA-F]+\s*,', (SRC / "elster" / "ElsterTable.h").read_text(encoding="utf-8"))
    # SG Ready values handled on the ESP (writable numbers and selects without a table row)
    signals += re.findall(r'\{"(SG_READY_[A-Z0-9_]+)"', header)
    out = set()
    for m in members:
        for s in signals:
            base = f"{m}_{s}".lower()
            out.update({base, base + "_set"})
    out.update(u[len("stiebel_"):] for u in re.findall(r'"(stiebel_(?:calculated|cop)_\w+)"', header))
    out.update({"climate_heizung", "climate_heizung_hk2", "climate_warmwasser"})
    for d in DAYS:
        out.update({f"ww_programm_{d}", f"heiz_programm_{d}", f"heiz_programm_hk2_{d}"})
    for y in SRC.glob("*.yaml"):
        for name in re.findall(r'^\s*(?:-\s*)?name:\s*"?([^"\n]+?)"?\s*$', y.read_text(encoding="utf-8"), re.M):
            out.add(slug(name))
    return out


def main() -> int:
    allowed = allowed_suffixes()
    problems = []
    for dash in sorted((ROOT / "dashboards").glob("*.yaml")):
        for n, line in enumerate(dash.read_text(encoding="utf-8").splitlines(), 1):
            if line.lstrip().startswith("#"):
                continue
            for eid in re.findall(rf"\b{DOMAINS}\.[a-z0-9_]+", line):
                obj = eid.split(".", 1)[1]
                if not obj.startswith(PREFIX) or obj[len(PREFIX):] not in allowed:
                    problems.append(f"{dash.relative_to(ROOT)}:{n}: {eid} is not generated by the firmware")
    for p in problems:
        print(p)
    print(f"{len(problems)} problem(s)")
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
